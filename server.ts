        newTask.steps = steps;
        newTask.currentStep = 2;

        let cleanPrompt = instruction
          .replace(/ဆွဲပေးပါ/g, "")
          .replace(/ပုံဆွဲပေးပါ/g, "")
          .replace(/ပုံဆွဲ/g, "")
          .replace(/^draw\s+/i, "")
          .replace(/^generate image of\s+/i, "")
          .replace(/^create image of\s+/i, "")
